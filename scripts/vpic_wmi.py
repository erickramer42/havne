#!/usr/bin/env python3
# File/layer: scripts/vpic_wmi.py | build tooling, generated data
# Testing: UNIT: --selftest (a made-up dump: the filters, the labels,
#          the order, the escapes, the refusals); its output is
#          core/src/vin_wmi_table.h, which VinTest (test_core) reads
#
# Writes core/src/vin_wmi_table.h (ADR-0043 section 2) from NHTSA's vPIC
# standalone database, the plain SQL release from
# https://vpic.nhtsa.dot.gov/downloads/ (vPICList_lite_YYYY_MM.plain.zip),
# read straight from the zip:
#
#   python -I scripts/vpic_wmi.py <vPICList_lite_YYYY_MM.plain.zip> [out]
#   python -I scripts/vpic_wmi.py --selftest
#
# The table holds each manufacturer code (WMI, 49 CFR 565.15(a): three
# characters, or six for a low-volume manufacturer, whose third is a 9)
# that vPIC lists for a vehicle other than a trailer, with the makes
# vPIC names under it. vPIC's data is the US government's, public
# information that "may be distributed or copied" (NHTSA's terms of
# use); the generated header says which release and the zip's SHA-256.

import hashlib
import io
import re
import sys
import zipfile

TRAILER = "6"   # vpic.vehicletype: a trailer has no ECU to read
WMI_OK = re.compile(r"[A-HJ-NPR-Z0-9]{2}([A-HJ-NPR-Z0-8]|9[A-HJ-NPR-Z0-9]{3})")
WANT = ("wmi", "wmi_make", "make")


def tables(lines):
    """The COPY blocks of WANT's tables, as lists of dicts by column."""
    out = {t: [] for t in WANT}
    cur = cols = None
    for line in lines:
        if cur is None:
            m = re.match(r"COPY vpic\.(\w+) \(([^)]*)\) FROM stdin;", line)
            if m and m.group(1) in out:
                cur = m.group(1)
                cols = [c.strip().strip('"') for c in m.group(2).split(",")]
            continue
        if line.startswith("\\."):
            cur = None
            continue
        out[cur].append(dict(zip(cols, line.rstrip("\n").split("\t"))))
    missing = [t for t in WANT if not out[t]]
    if missing:
        raise SystemExit(f"vpic_wmi: no rows for {', '.join(missing)}: not a vPIC dump?")
    return out


def label(makes):
    """'Ford'; 'Ford or Lincoln'; 'Datsun, Infiniti or Nissan'."""
    names = sorted({m.strip() for m in makes if m.strip()}, key=lambda s: (s.casefold(), s))
    if len(names) <= 1:
        return names[0] if names else ""
    return ", ".join(names[:-1]) + " or " + names[-1]


def rows(t):
    """[(code, label)] sorted by code, and how many vPIC rows were left out."""
    make = {r["id"]: r["name"] for r in t["make"]}
    makes_of = {}
    for r in t["wmi_make"]:
        makes_of.setdefault(r["wmiid"], []).append(make[r["makeid"]])
    out, seen, skipped = [], set(), {"trailer": 0, "not a WMI": 0, "no make": 0}
    for r in t["wmi"]:
        code = r["wmi"]
        if r["vehicletypeid"] == TRAILER:
            skipped["trailer"] += 1
            continue
        if not WMI_OK.fullmatch(code):
            skipped["not a WMI"] += 1   # vPIC holds a few with an O
            continue
        name = label(makes_of.get(r["id"], []))
        if not name:
            skipped["no make"] += 1
            continue
        if any(ord(c) < 32 or ord(c) > 126 for c in name):
            raise SystemExit(f"vpic_wmi: {code}'s makes aren't plain ASCII: {name!r}")
        if code in seen:
            raise SystemExit(f"vpic_wmi: {code} listed twice")
        seen.add(code)
        out.append((code, name))
    out.sort()
    return out, skipped


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def header(entries, release, sha256):
    labels = sorted({name for _, name in entries})
    index = {name: i for i, name in enumerate(labels)}
    out = io.StringIO()
    w = out.write
    w("// File/layer: core/src/vin_wmi_table.h | core internals, generated data\n")
    w("// Testing: UNIT: VinTest (test_core): known codes found, the order\n")
    w("//          checked at compile time (core/src/vin.cpp)\n")
    w("//\n")
    w("// Generated by scripts/vpic_wmi.py; rerun it on a newer release rather\n")
    w("// than editing. From NHTSA's vPIC standalone database:\n")
    w(f"// {release}, the plain SQL zip from\n")
    w("// https://vpic.nhtsa.dot.gov/downloads/,\n")
    w(f"// SHA-256 {sha256}.\n")
    w("// Each manufacturer code (WMI) vPIC lists for a vehicle other than a\n")
    w("// trailer, with the makes vPIC names under it (ADR-0043 section 2).\n")
    w("\n")
    w("#ifndef ECUIO_VIN_WMI_TABLE_H\n#define ECUIO_VIN_WMI_TABLE_H\n\n")
    w("#include <cstdint>\n\n")
    w("namespace ecuio_vin {\n\n")
    w(f"constexpr const char* kVpicRelease = {c_string(release)};\n\n")
    w("// Each code's makes, joined for display\n")
    w("constexpr const char* const kMakes[] = {\n")
    for name in labels:
        w(f"    {c_string(name)},\n")
    w("};\n\n")
    w("// Three characters, or six (positions 1-3 and 12-14) when the third is\n")
    w("// a 9; sorted by code, kMakes' index beside it\n")
    w("struct Wmi {\n    char code[7];\n    std::uint16_t make;\n};\n\n")
    w("constexpr Wmi kWmis[] = {\n")
    for code, name in entries:
        w(f'    {{"{code}", {index[name]}}},\n')
    w("};\n\n")
    w("} // namespace ecuio_vin\n\n#endif // ECUIO_VIN_WMI_TABLE_H\n")
    if len(labels) > 0xFFFF:
        raise SystemExit("vpic_wmi: more labels than a uint16_t indexes")
    return out.getvalue()


def from_zip(path):
    with open(path, "rb") as f:
        sha256 = hashlib.file_digest(f, "sha256").hexdigest()
    with zipfile.ZipFile(path) as z:
        sql = [n for n in z.namelist() if n.endswith(".sql")]
        if len(sql) != 1:
            raise SystemExit(f"vpic_wmi: {path} holds {len(sql)} .sql files, not one")
        release = sql[0].rsplit("/", 1)[-1][:-4]
        with z.open(sql[0]) as raw:
            t = tables(io.TextIOWrapper(raw, encoding="utf-8", errors="replace"))
    return t, release, sha256


