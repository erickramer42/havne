def selftest():
    t = tables(io.StringIO(SAMPLE))
    entries, skipped = rows(t)
    checks = [
        ("sorted by code", [c for c, _ in entries] == ["1A9596", "1FA", "1FM", "JN1"]),
        ("makes deduped, sorted, joined", dict(entries)["JN1"] == "datsun, Infiniti or Nissan"),
        ("a six-character code kept, its name trimmed", dict(entries)["1A9596"] == 'Small "Q" Motors'),
        ("a trailer left out", skipped["trailer"] == 1),
        ("an O, and a short code with a 9, left out", skipped["not a WMI"] == 2),
        ("label", label(["Ford", "Lincoln"]) == "Ford or Lincoln"),
    ]
    text = header(entries, "vPICList_lite_TEST", "0" * 64)
    checks += [
        ("quotes escaped", '"Small \\"Q\\" Motors",' in text),
        ("one label shared", text.count('"Ford",') == 1 and '{"1FM", 0}' in text and '{"1FA", 0}' in text),
        ("release named", 'kVpicRelease = "vPICList_lite_TEST"' in text),
    ]
    try:
        rows(tables(io.StringIO(SAMPLE.replace("16\t1FM", "16\t1FA"))))
        checks.append(("a code twice refused", False))
    except SystemExit:
        checks.append(("a code twice refused", True))
    try:
        rows(tables(io.StringIO(SAMPLE.replace("1\tFord", "1\tMazéda"))))
        checks.append(("a non-ASCII make refused", False))
    except SystemExit:
        checks.append(("a non-ASCII make refused", True))
    failed = [name for name, ok in checks if not ok]
    for name, ok in checks:
        print(("ok    " if ok else "FAIL  ") + name)
    print(f"{len(checks) - len(failed)}/{len(checks)} passed")
    return 1 if failed else 0


def main(argv):
    if argv[1:] == ["--selftest"]:
        return selftest()
    if len(argv) not in (2, 3):
        print(__doc__ or "usage: vpic_wmi.py <vPICList_lite_YYYY_MM.plain.zip> [out]", file=sys.stderr)
        return 2
    t, release, sha256 = from_zip(argv[1])
    entries, skipped = rows(t)
    out = argv[2] if len(argv) == 3 else "core/src/vin_wmi_table.h"
    with open(out, "w", encoding="ascii", newline="\n") as f:
        f.write(header(entries, release, sha256))
    left = ", ".join(f"{n} {why}" for why, n in skipped.items() if n)
    print(f"{out}: {len(entries)} codes from {release} ({left} left out)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
