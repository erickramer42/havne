#!/usr/bin/env python3
# File/layer: scripts/dtc_titles.py | build tooling, generated data
# Testing: UNIT: --selftest (made-up source files: the ranges kept, the
#          characters mapped, the order, the escapes, the refusals); its
#          output is core/src/dtc_titles_table.h, which DtcTitleTest
#          (test_obd2) reads
#
# Writes core/src/dtc_titles_table.h (ADR-0044) from Wal33D's
# dtc-database (https://github.com/Wal33D/dtc-database, MIT): its
# data/source-data/p_codes.txt and u_codes.txt ("P0301 - Title" lines)
# and its LICENSE, from one commit:
#
#   python -I scripts/dtc_titles.py <source-data dir> <LICENSE> <commit> [out]
#   python -I scripts/dtc_titles.py --selftest
#
# Kept: SAE J2012's own ranges of powertrain and network codes, P0, P2,
# P34-P39, U0 and U3; a manufacturer's ranges (P1, P30-P33, U1, U2) and
# every body and chassis code are left out. Curly quotes become straight
# ones and an en dash a hyphen, so core's strings stay ASCII.

import hashlib
import io
import os
import re
import sys

LINE = re.compile(r"([PU])([0-9A-F]{4}) - (.+)")
CODE_ONLY = re.compile(r"[PCBU][0-9A-F]{4}")
MAP = {"\u201c": '"', "\u201d": '"', "\u2018": "'", "\u2019": "'", "\u2013": "-"}
LETTER = {"P": 0, "C": 1, "B": 2, "U": 3}


def sae(letter, digits):
    """J2012's ranges SAE controls, of the two letters kept"""
    if letter == "P":
        return digits[0] in "02" or (digits[0] == "3" and digits[1] in "456789")
    return digits[0] in "03"


def code_value(letter, digits):
    return LETTER[letter] << 14 | int(digits, 16)


def read(lines, name):
    """[(value, "P0301", title)] of one file, the lines in a manufacturer's
    range, and the lines whose title is only a code (a slip in the source:
    "P3400 - P34C8" above P3400's own line)"""
    out, skipped, slips = [], 0, 0
    for n, raw in enumerate(lines, 1):
        raw = raw.rstrip("\r\n")
        if not raw.strip():
            continue
        m = LINE.fullmatch(raw.strip())
        if not m:
            raise SystemExit(f"dtc_titles: {name}:{n}: not 'CODE - Title': {raw!r}")
        letter, digits, title = m.groups()
        if not sae(letter, digits):
            skipped += 1
            continue
        if CODE_ONLY.fullmatch(title.strip()):
            slips += 1
            continue
        for k, v in MAP.items():
            title = title.replace(k, v)
        title = " ".join(title.split())
        if any(ord(c) < 32 or ord(c) > 126 for c in title):
            raise SystemExit(f"dtc_titles: {name}:{n}: {letter}{digits}'s title isn't plain ASCII: {title!r}")
        out.append((code_value(letter, digits), letter + digits, title))
    return out, skipped, slips


def entries(files):
    """files: [(name, lines)]; every entry, sorted, and the counts left out"""
    rows, skipped, slips, seen = [], 0, 0, {}
    for name, lines in files:
        got, s, k = read(lines, name)
        skipped += s
        slips += k
        for value, code, title in got:
            if value in seen:
                raise SystemExit(f"dtc_titles: {code} listed twice ({seen[value]!r}, {title!r})")
            seen[value] = title
            rows.append((value, code, title))
    rows.sort()
    return rows, skipped, slips


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def header(rows, commit, digests, license_text):
    out = io.StringIO()
    w = out.write
    w("// File/layer: core/src/dtc_titles_table.h | core internals, generated data\n")
    w("// Testing: UNIT: DtcTitleTest (test_obd2): titles found, ranges left\n")
    w("//          out; the order checked at compile time (core/src/dtc_titles.cpp)\n")
    w("//\n")
    w("// Generated by scripts/dtc_titles.py; rerun it on a newer commit rather\n")
    w("// than editing. From Wal33D's dtc-database,\n")
    w("// https://github.com/Wal33D/dtc-database, commit\n")
    w(f"// {commit}:\n")
    for name, digest in digests:
        w(f"// data/source-data/{name} SHA-256 {digest}\n")
    w("// The generic titles of SAE J2012's powertrain and network ranges (P0,\n")
    w("// P2, P34-P39, U0, U3; ADR-0044), under the project's license:\n")
    w("//\n")
    for line in license_text.strip().splitlines():
        w(("// " + line).rstrip() + "\n")
    w("\n")
    w("#ifndef ECUIO_DTC_TITLES_TABLE_H\n#define ECUIO_DTC_TITLES_TABLE_H\n\n")
    w("#include <cstdint>\n\n")
    w("namespace ecuio_dtc {\n\n")
    w(f"constexpr const char* kTitlesSource = {c_string('Wal33D/dtc-database ' + commit[:7])};\n\n")
    # The notice MIT asks for in every copy, compiled in, so each binary
    # that holds the titles holds it too
    w("// The project's copyright and permission notice, as its LICENSE has it\n")
    w("constexpr const char* kTitlesNotice =\n")
    notice = license_text.strip().splitlines()
    for i, line in enumerate(notice):
        end = "\\n" if i < len(notice) - 1 else ""
        w(f"    {c_string(line)[:-1]}{end}\"{';' if i == len(notice) - 1 else ''}\n")
    w("\n")
    w("struct Title {\n    std::uint16_t code;   // as Service 03 carries it\n    const char* title;\n};\n\n")
    w("// Sorted by code\n")
    w("constexpr Title kTitles[] = {\n")
    for value, code, title in rows:
        w(f"    {{0x{value:04X}, {c_string(title)}}}, // {code}\n")
    w("};\n\n")
    w("} // namespace ecuio_dtc\n\n#endif // ECUIO_DTC_TITLES_TABLE_H\n")
    return out.getvalue()


def selftest():
    p = ["P0301 - Cylinder 1 Misfire Detected", "P1234 - A Maker's Own",
         "P3400 - Cylinder Deactivation System Bank 1", "P3000 - A Maker's Too",
         "P2110 - Throttle Actuator A Control System \u2013 Forced Limited RPM",
         "", "P3400 - P34C8", "P0127 - Intake Air Temperature Too High \"Bank\" \u201cA\u201d"]
    u = ["U0100 - Lost Communication With ECM/PCM A", "U1000 - A Maker's Network",
         "U3000 - Control Module"]
    rows, skipped, slips = entries([("p", p), ("u", u)])
    codes = [c for _, c, _ in rows]
    titles = {c: t for _, c, t in rows}
    checks = [
        ("SAE ranges kept, by value", codes == ["P0127", "P0301", "P2110", "P3400", "U0100", "U3000"]),
        ("a manufacturer's ranges left out", skipped == 3),
        ("a title that is a code left out, the real one kept",
         slips == 1 and titles["P3400"] == "Cylinder Deactivation System Bank 1"),
        ("an en dash a hyphen", titles["P2110"].endswith("System - Forced Limited RPM")),
        ("curly quotes straight", titles["P0127"].endswith('"A"')),
        ("U0100's value", [v for v, c, _ in rows if c == "U0100"] == [0xC100]),
    ]
    text = header(rows, "0" * 40, [("p_codes.txt", "1" * 64)], "MIT License\n\nCopyright (c) X")
    checks += [
        ("quotes escaped", '{0x0127, "Intake Air Temperature Too High \\"Bank\\" \\"A\\""}, // P0127' in text),
        ("the license carried", "// MIT License\n//\n// Copyright (c) X\n" in text),
        ("the source named", 'kTitlesSource = "Wal33D/dtc-database 0000000"' in text),
        ("the notice compiled in, line by line",
         'kTitlesNotice =\n    "MIT License\\n"\n    "\\n"\n    "Copyright (c) X";\n' in text),
    ]
    for name, bad in [("a code twice refused", p + ["P0301 - Again"]),
                      ("a line not a code refused", p + ["P03O1 - Letter O"]),
                      ("a non-ASCII title refused", p + ["P0302 - Cylinder 2 Misfire \u00e9"])]:
        try:
            entries([("p", bad)])
            checks.append((name, False))
        except SystemExit:
            checks.append((name, True))
    failed = [n for n, ok in checks if not ok]
    for n, ok in checks:
        print(("ok    " if ok else "FAIL  ") + n)
    print(f"{len(checks) - len(failed)}/{len(checks)} passed")
    return 1 if failed else 0


def main(argv):
    if argv[1:] == ["--selftest"]:
        return selftest()
    if len(argv) not in (4, 5):
        print("usage: dtc_titles.py <source-data dir> <LICENSE> <commit> [out]", file=sys.stderr)
        return 2
    src, license_path, commit = argv[1], argv[2], argv[3]
    if not re.fullmatch(r"[0-9a-f]{40}", commit):
        print("dtc_titles: the commit is its full 40-digit hash", file=sys.stderr)
        return 2
    files, digests = [], []
    for name in ("p_codes.txt", "u_codes.txt"):
        data = open(os.path.join(src, name), "rb").read()
        digests.append((name, hashlib.sha256(data).hexdigest()))
        files.append((name, data.decode("utf-8").splitlines()))
    rows, skipped, slips = entries(files)
    license_text = open(license_path, encoding="utf-8").read()
    out = argv[4] if len(argv) == 5 else "core/src/dtc_titles_table.h"
    with open(out, "w", encoding="ascii", newline="\n") as f:
        f.write(header(rows, commit, digests, license_text))
    print(f"{out}: {len(rows)} titles from {commit[:7]} ({skipped} in a manufacturer's range and {slips} titled with a code left out)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
