// stream's paragraph, after the synopsis
void usage_stream(FILE* to)
{
    std::fprintf(
        to,
        "stream   opens the session <uri> names (mock://, replay://, "
        "elm327://,\n"
        "         j2534:// on Windows, socketcan:// on Linux) and writes its\n"
        "         frames as JSON lines;\n"
        "         --values adds the values its profile decodes. Ends at "
        "Ctrl+C,\n"
        "         after N frames, after S seconds, or at a replay's last "
        "frame;\n"
        "         --until-scanned also once uds-generic's did= ranges are "
        "asked.\n"
        "         --record writes the session to a folder of its own in "
        "<folder>\n"
        "         (frames.csv, signals.csv, events.log), named for when it\n"
        "         started and the --label; each line typed meanwhile marks "
        "it.\n"
        "         --signals loads a signal file (stream and sim alike): its\n"
        "         profile, user.<name>, is the URI's when it names none.\n"
        "         A replay:// with neither reads with its recording's own\n"
        "         signals.json when its hash still matches and the URI\n"
        "         selects the recorded profile or none.\n"
        "         --conditions attaches a condition file: a conditions\n"
        "         line says which of its conditions the session can judge,\n"
        "         and a condition line follows each change, at its own time;\n"
        "         the end line's conditions_dropped counts the changes whose\n"
        "         line was dropped, with its frame or alone. The conditions\n"
        "         line comes again when a condition's signal turns out not\n"
        "         received, or arrives after all. A replay:// with no\n"
        "         --conditions judges by its recording's own conditions.json\n"
        "         when its hash still matches (the line's source says\n"
        "         recording).\n"
        "         --plugin loads a plugin (a folder or a packed file) and\n"
        "         registers its variants as plugin.<id>.<variant>; the URI's\n"
        "         profile= names the one to read. A plugin that talks to\n"
        "         a car (elm327://, j2534://) runs only with your consent\n"
        "         in the store (plugins consent; --consent-store names\n"
        "         another than the app's), and the session line says it;\n"
        "         without one nothing is sent, and the refusal says what\n"
        "         to read and run. log takes it the same way.\n"
        "         --together reads profiles as one set, merged in the\n"
        "         order named: obd2 (its signals) or obd2-modules (its\n"
        "         modules alone, so the emissions codes are still read),\n"
        "         a --plugin's variants and --signals files' profiles;\n"
        "         --plugin and --signals may then each be given more than\n"
        "         once. The session line names them and the merged set, a\n"
        "         note line follows for each thing the merge did, and no\n"
        "         plugin's code runs. log, sim and view --frames take it\n"
        "         the same way.\n"
        "         --unlock asks one security access level of one module the\n"
        "         plugin's code talks to (its ECU id and the level in hex,\n"
        "         one the plugin declares for it): once, when the code\n"
        "         talks, never again in the run. An unlock line says how\n"
        "         core took it, and a conversation line follows each change\n"
        "         of a module's report (state, level, outcome, failed\n"
        "         attempts, delay left). The attempts are counted in the\n"
        "         app's security.json, or the --security-store named, by\n"
        "         the module's serial, else the car's VIN, else --vehicle.\n"
        "         --pick ranked asks only the profile's ranked signals (the\n"
        "         ones a UI plots first: the app's default pick without its\n"
        "         gauges and ticks), and a focus line names them; a profile\n"
        "         that ranks none, a session that asks nothing (the mock, a\n"
        "         replay) and a pick core refuses leave the whole set asked,\n"
        "         said on standard error; a profile asked only what is\n"
        "         picked (a car-sized set) asks none then.\n"
        "         An adapter or a CAN interface holds the computer from\n"
        "         sleeping on its idle timer until the end, and the session\n"
        "         line says so (awake); --allow-sleep lets it sleep. A closed\n"
        "         lid still sleeps it. log holds it the same way.\n");
}

// log's paragraph, after stream's
void usage_log(FILE* to)
{
    std::fprintf(
        to,
        "log      records the session <uri> names to a folder of its own in\n"
        "         <folder>, as stream --record does, asking only the signals\n"
        "         --signal names (every one with none) so each is read as\n"
        "         often as the bus allows; export then takes those columns\n"
        "         by itself. --pick ranked adds the profile's ranked signals\n"
        "         to them, the recording naming them a pick, not a log's\n"
        "         focus; on a profile that ranks none or a session that asks\n"
        "         nothing it adds none (no names: the whole set, but a\n"
        "         profile asked only what is picked needs --signal or\n"
        "         --conditions). Writes a\n"
        "         log line every 10 s with the recording's size, no frames\n"
        "         or values. Runs until Ctrl+C, S seconds, a failed recording\n"
        "         or a replay's last frame; a lost link is logged and waited\n"
        "         out. --signals, --plugin and --conditions as stream's: the\n"
        "         recording holds the conditions' copy and each change, and\n"
        "         no condition line is written; a replay's own copy is\n"
        "         stream's alone. --armed writes only around the conditions\n"
        "         with record: a folder per window, from the condition's\n"
        "         before ahead of it to its after past the end, a recording\n"
        "         line as each opens (its folder) and as the log is armed\n"
        "         again; a file with no enabled condition that records is\n"
        "         refused at the start.\n");
}

